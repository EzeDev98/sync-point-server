-- Baseline schema for Flyway, reconstructed from the 10 JPA entities as
-- they stood at the time this migration was written.
--
-- IMPORTANT: with spring.flyway.baseline-on-migrate=true and
-- spring.flyway.baseline-version=1 (see application-prod.properties),
-- Flyway will NOT execute this script against the existing production
-- database -- it only records version 1 as already applied, since that
-- database's schema already exists (built incrementally by Hibernate's
-- ddl-auto=update up to this point). This script's purpose is:
--   1. Documentation of the schema as of the Flyway cutover.
--   2. The authoritative source for building any NEW environment
--      (staging, disaster recovery, a fresh dev database) from scratch.
--
-- CAVEAT -- read before relying on this for a new environment:
-- This was reconstructed by hand from JPA @Column/@Table annotations,
-- not exported from the live database. Two things could not be
-- determined from the entity code alone and should be verified against
-- the real production schema (e.g. via \d+ <table> in psql) before this
-- script is used to build any environment that must match production:
--   - SystemWallet and WalletFundingRecord's BigDecimal columns have no
--     explicit @Column(precision=, scale=) -- unlike every other money
--     column in this codebase, which uses MoneyConfig (15,2). They are
--     given NUMERIC(15,2) below to match that convention, but Hibernate
--     may have generated a different default when these tables were
--     first created.
--   - Exact VARCHAR lengths for unannotated String columns are assumed
--     to be Hibernate's default (255).

-- =========================================================
-- users
-- =========================================================
CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keycloak_id    VARCHAR(255),
    user_ref_id    VARCHAR(255),
    first_name     VARCHAR(255),
    middle_name    VARCHAR(255),
    last_name      VARCHAR(255),
    username       VARCHAR(255),
    password       VARCHAR(255),
    email          VARCHAR(255),
    phone_number   VARCHAR(255),
    gender         VARCHAR(255),
    age            INTEGER NOT NULL,
    status         VARCHAR(255) NOT NULL,
    date_of_birth  VARCHAR(255),
    created_at     TIMESTAMP
);

-- =========================================================
-- wallets  (OneToOne owner side -> users.id, unique FK)
-- =========================================================
CREATE TABLE wallets (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id                VARCHAR(255),
    pin                      VARCHAR(255),
    wallet_phone_number      VARCHAR(255),
    offline_limit            NUMERIC(15,2),
    status                   BOOLEAN NOT NULL,
    mirror_balance           NUMERIC(15,2),
    pin_last_changed         TIMESTAMP,
    pin_attempts             INTEGER,
    pin_change_attempts      INTEGER,
    last_pin_change_attempt  TIMESTAMP,
    is_locked                BOOLEAN,
    locked_until             TIMESTAMP,
    login_attempts           INTEGER,
    last_login_attempt       TIMESTAMP,
    login_lock_until         TIMESTAMP,
    user_id                  BIGINT NOT NULL UNIQUE REFERENCES users(id),
    created_at               TIMESTAMP,
    updated_at               TIMESTAMP
);

-- =========================================================
-- transactions
-- =========================================================
CREATE TABLE transactions (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference         VARCHAR(255) NOT NULL,
    request_ref                   VARCHAR(255) NOT NULL,
    transaction_type              VARCHAR(255) NOT NULL,
    entry_type                    VARCHAR(255) NOT NULL,
    currency                      VARCHAR(3) NOT NULL,
    sender_wallet_id              VARCHAR(255),
    sender_name                   VARCHAR(255),
    sender_wallet_phone_number    VARCHAR(255),
    sender_balance_before         NUMERIC(15,2),
    sender_balance_after          NUMERIC(15,2),
    receiver_wallet_id            VARCHAR(255),
    receiver_name                 VARCHAR(255),
    receiver_wallet_phone_number  VARCHAR(255),
    receiver_balance_before       NUMERIC(15,2),
    receiver_balance_after        NUMERIC(15,2),
    amount                        NUMERIC(15,2) NOT NULL,
    description                   VARCHAR(255),
    status                        VARCHAR(255) NOT NULL,
    sync_id                       VARCHAR(255),
    synced_at                     TIMESTAMP,
    created_at                    TIMESTAMP NOT NULL,
    completed_at                  TIMESTAMP,
    failure_reason                VARCHAR(255),
    version                       BIGINT,
    CONSTRAINT uk_request_ref_entry_type UNIQUE (request_ref, entry_type)
);

CREATE INDEX idx_transaction_reference ON transactions (transaction_reference);
CREATE INDEX idx_sender_wallet_phone   ON transactions (sender_wallet_phone_number);
CREATE INDEX idx_receiver_wallet_phone ON transactions (receiver_wallet_phone_number);
CREATE INDEX idx_status                ON transactions (status);
CREATE INDEX idx_created_at            ON transactions (created_at);
CREATE INDEX idx_request_ref           ON transactions (request_ref);

-- =========================================================
-- system_wallet
-- =========================================================
CREATE TABLE system_wallet (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id             VARCHAR(255) NOT NULL UNIQUE,
    name                  VARCHAR(255),
    phone_number          VARCHAR(255),
    initial_fund          NUMERIC(15,2) NOT NULL,
    available_balance     NUMERIC(15,2) NOT NULL,
    total_disbursed       NUMERIC(15,2) NOT NULL,
    total_reclaimed       NUMERIC(15,2) NOT NULL,
    total_users_funded    BIGINT NOT NULL,
    active_funded_users   BIGINT NOT NULL,
    current_liability     NUMERIC(15,2) NOT NULL,
    version               BIGINT,
    created_at            TIMESTAMP,
    updated_at            TIMESTAMP
);

-- =========================================================
-- wallet_funding_record
-- =========================================================
CREATE TABLE wallet_funding_record (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT,
    wallet_id     VARCHAR(255),
    amount        NUMERIC(15,2),
    reclaimed     BOOLEAN NOT NULL,
    funded_at     TIMESTAMP,
    reclaimed_at  TIMESTAMP
);

CREATE INDEX idx_wallet_funding_user_id   ON wallet_funding_record (user_id);
CREATE INDEX idx_wallet_funding_wallet_id ON wallet_funding_record (wallet_id);
CREATE INDEX idx_wallet_funding_reclaimed ON wallet_funding_record (reclaimed);

-- =========================================================
-- user_sessions
-- =========================================================
CREATE TABLE user_sessions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL,
    phone_number  VARCHAR(255) NOT NULL,
